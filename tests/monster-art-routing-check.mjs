import assert from "node:assert/strict";
import { access, readFile } from "node:fs/promises";

let artRegistry = null;
try {
  artRegistry = await import("../src/data/monster-art-definitions.js");
} catch {
  // The first TDD run must fail here until the approved runtime registry exists.
}

assert.ok(artRegistry, "Approved Zone 2–4 monster art needs a data-owned runtime registry.");

const {
  MONSTER_ART_DEFINITIONS,
  MONSTER_ART_KEY_BY_ID,
  MONSTER_ANIMATION_DEFINITIONS,
  getMonsterStripSource,
  isDedicatedMonsterArtKey,
} = artRegistry;

const expectedRoutes = {
  "archive-raider": "zone2ArchiveSaboteur",
  "archive-marksman": "zone2CipherMarksman",
  "archive-chanter": "zone2CorruptedArchivist",
  "archive-shadow-curator": "zone2ShadowCurator",
  "crossroads-raider": "zone3BridgeRaider",
  "crossroads-marksman": "zone3FactionSkirmisher",
  "crossroads-chanter": "zone3WhisperPropagandist",
  "southern-tyrant": "zone3SouthernTyrant",
  "spring-raider": "zone4CropSaboteur",
  "spring-marksman": "zone4BureauMarksman",
  "spring-chanter": "zone4RationChanter",
  "spring-bureaucracy-beast": "zone4BureaucracyBeast",
};

assert.deepEqual(MONSTER_ART_KEY_BY_ID, expectedRoutes, "Every approved monster ID must route to its own art key.");
assert.deepEqual(Object.keys(MONSTER_ART_DEFINITIONS), Object.values(expectedRoutes), "The registry must contain exactly the approved twelve packs.");
assert.deepEqual(MONSTER_ANIMATION_DEFINITIONS, {
  idle: { frameWidth: 64, frameHeight: 64, frameCount: 4, frameDuration: 420 },
  run: { frameWidth: 64, frameHeight: 64, frameCount: 4, frameDuration: 110 },
  attack: { frameWidth: 64, frameHeight: 64, frameCount: 4, frameDuration: 65 },
  hurt: { frameWidth: 64, frameHeight: 64, frameCount: 3, frameDuration: 60 },
  death: { frameWidth: 64, frameHeight: 64, frameCount: 6, frameDuration: 90 },
});

for (const [monsterId, artKey] of Object.entries(expectedRoutes)) {
  const definition = MONSTER_ART_DEFINITIONS[artKey];
  assert.ok(isDedicatedMonsterArtKey(artKey), `${monsterId} must be treated as dedicated, non-fallback art.`);
  assert.equal(definition.group, artKey.slice(0, 5).toLowerCase(), `${monsterId} must load with its zone group.`);
  assert.equal(definition.directional, true);
  assert.equal(definition.directionalAnimation, true);
  assert.equal(definition.flipForFacing, true);
  assert.equal(definition.drawWidth, definition.boss ? 60 : 48);
  assert.equal(definition.drawHeight, definition.boss ? 60 : 48);

  assert.match(getMonsterStripSource(artKey, "south", "run"), /-south-walk\.png$/, "Runtime run must load the authored walk strip.");
  assert.equal(
    getMonsterStripSource(artKey, "west", "attack"),
    getMonsterStripSource(artKey, "east", "attack"),
    "West must mirror the east strip instead of requiring drift-prone duplicate art.",
  );

  for (const direction of ["south", "north", "east"]) {
    for (const state of Object.keys(MONSTER_ANIMATION_DEFINITIONS)) {
      const source = getMonsterStripSource(artKey, direction, state);
      await access(new URL(`../${source}`, import.meta.url));
    }
  }
}

const [runtime, manifest] = await Promise.all([
  readFile(new URL("../src/runtime/game-runtime.js", import.meta.url), "utf8"),
  readFile(new URL("../src/data/asset-manifest.js", import.meta.url), "utf8"),
]);

assert.match(runtime, /MONSTER_ART_KEY_BY_ID\[monster\.id\]/, "Runtime routing must use the exact monster ID map.");
assert.match(runtime, /loadDedicatedMonsterSprites/, "Approved pack paths must be generated by one loader.");
assert.match(runtime, /isDedicatedMonsterArtKey\(artKey\)/, "Dedicated art must explicitly block generic renderer fallbacks.");
assert.match(manifest, /assets\\?\/monsters\\?\/zone2-/, "Zone 2 packs must belong to the Zone 2 critical load group.");
assert.match(manifest, /assets\\?\/monsters\\?\/zone3-/, "Zone 3 packs must belong to the Zone 3 critical load group.");
assert.match(manifest, /assets\\?\/monsters\\?\/zone4-/, "Zone 4 packs must belong to the Zone 4 critical load group.");

console.log("PASS: all twelve approved Zone 2–4 monster packs route without generic fallbacks.");
